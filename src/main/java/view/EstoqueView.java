    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Estoque e =
        new Estoque();

        e.setNomeItem(
        txtNomeMedicamento.getText());

        e.setQuantidade(
        Integer.parseInt(
        txtQuantidade.getText()));

        e.setUnidadeMedida(
        txtUnidade.getText());

        e.setQuantidadeMinima(
        Integer.parseInt(
        txtQuantidadeMinima.getText()));

        EstoqueDAO dao =
        new EstoqueDAO();

        dao.salvar(e);

        carregarTabela();

        limparCampos();

        JOptionPane.showMessageDialog(
        null,
        "Item salvo!");// TODO add your handling code here:
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnAtualizarQuantidadeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarQuantidadeActionPerformed
        int linha =
        tblEstoque.getSelectedRow();

        if(linha == -1) {

            JOptionPane.showMessageDialog(
            null,
            "Selecione um item");

            return;
        }

        int id = Integer.parseInt(

        tblEstoque.getValueAt(
        linha,
        0).toString());

        int quantidade = Integer.parseInt(

        JOptionPane.showInputDialog(
        "Nova quantidade"));

        EstoqueDAO dao =
        new EstoqueDAO();

        dao.atualizarQuantidade(
        id,
        quantidade);

        carregarTabela();

        JOptionPane.showMessageDialog(
        null,
        "Quantidade atualizada!");// TODO add your handling code here:
    }//GEN-LAST:event_btnAtualizarQuantidadeActionPerformed

