    public void carregarTabela() {

        try {

            EstoqueDAO dao =
            new EstoqueDAO();

            ResultSet rs =
            dao.listar();

            DefaultTableModel modelo =

            (DefaultTableModel)
            tblEstoque.getModel();

            modelo.setRowCount(0);

            while(rs.next()) {

                modelo.addRow(new Object[] {

                    rs.getInt("item_id"),
                    rs.getString("nome_item"),
                    rs.getInt("quantidade"),
                    rs.getString("unidade_medida"),
                    rs.getInt("quantidade_minima")

                });

            }

        } catch (Exception e) {

            System.out.println(
            "Erro tabela estoque: "
            + e.getMessage());

        }

    }
