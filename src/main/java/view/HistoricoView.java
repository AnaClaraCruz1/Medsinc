    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        HistoricoMedico h =
        new HistoricoMedico();

        h.setPacienteId(
        Integer.parseInt(
        txtPacienteID.getText()));

        String medicoSelecionado =
        cbMedico.getSelectedItem()
        .toString();

        int medicoId =
        Integer.parseInt(
        medicoSelecionado.split(" - ")[0]);

        h.setMedicoId(medicoId);

        h.setDescricao(
        txtDescricao.getText());

        String dataBr =
        txtData.getText().trim();

        if(!dataBr.contains("/")) {

            JOptionPane.showMessageDialog(
            null,
            "Digite a data no formato DD/MM/AAAA");

            return;
        }

        String[] partes =
        dataBr.split("/");

        if(partes.length != 3) {

            JOptionPane.showMessageDialog(
            null,
            "Data inválida!");

            return;
        }

        String dataMysql =

        partes[2] + "-" +
        partes[1] + "-" +
        partes[0];

        h.setData(dataMysql);

        HistoricoDAO dao =
        new HistoricoDAO();

        dao.salvar(h);

        carregarTabela();

        limparCampos();

        JOptionPane.showMessageDialog(
        null,
        "Histórico salvo!");// TODO add your handling code here:
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha =
        tblHistoricos.getSelectedRow();

        if(linha == -1) {

            JOptionPane.showMessageDialog(
            null,
            "Selecione um histórico");

            return;
        }

        int id = Integer.parseInt(

        tblHistoricos.getValueAt(
        linha,
        0).toString());

        HistoricoDAO dao =
        new HistoricoDAO();

        dao.excluirHistorico(id);

        carregarTabela();

        JOptionPane.showMessageDialog(
        null,
        "Histórico excluído!");// TODO add your handling code here:
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnPesquisarPacienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarPacienteActionPerformed
        try {

            String nome =
            txtPesquisaPaciente.getText();

            PacienteDAO dao =
            new PacienteDAO();

            ResultSet rs =
            dao.pesquisarPaciente(nome);

            if(rs.next()) {

                txtPacienteID.setText(
                rs.getString("paciente_id"));

                JOptionPane.showMessageDialog(
                null,
                "Paciente encontrado!");

            } else {

                JOptionPane.showMessageDialog(
                null,
                "Paciente não encontrado");

            }

        } catch (Exception e) {

            System.out.println(
            "Erro pesquisa paciente: "
            + e.getMessage());

        }// TODO add your handling code here:
    }//GEN-LAST:event_btnPesquisarPacienteActionPerformed

