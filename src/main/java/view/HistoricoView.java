    public void carregarTabela() {

    try {

        HistoricoDAO dao =
        new HistoricoDAO();

        ResultSet rs =
        dao.listarHistoricos();

        DefaultTableModel modelo =
        (DefaultTableModel)
        tblHistoricos.getModel();

        modelo.setRowCount(0);

        while(rs.next()) {

            modelo.addRow(new Object[] {

                rs.getInt("historico_id"),
                rs.getString("paciente"),
                rs.getString("medico"),
                rs.getString("descricao"),
                rs.getString("data_registro")

            });

        }

    } catch (Exception e) {

        System.out.println(
        "Erro tabela histórico: "
        + e.getMessage());

    }
    }
    
    public void carregarMedicos() {

    try {

        Connection conn =
        Conexao.conectar();

        String sql =
        "SELECT usuario_id, nome FROM usuarios WHERE perfil='medico'";

        PreparedStatement stmt =
        conn.prepareStatement(sql);

        ResultSet rs =
        stmt.executeQuery();

        cbMedico.removeAllItems();

        while(rs.next()) {

            cbMedico.addItem(

            rs.getInt("usuario_id")
            + " - " +
            rs.getString("nome")

            );

        }
        cbMedico.setSelectedIndex(-1);

    } catch (Exception e) {

        System.out.println(
        "Erro carregar médicos: "
        + e.getMessage());

    }
    }
    

